// แนะนำเป็น ".1 รอคิวซ่อม" ก่อนเสมอ (เพิ่งคัดแยกเสร็จ ยังไม่เริ่มลงมือจริง)
export function suggestRepairStatus(item) {
  if (item?.category === 'vehicle') {
    return item.vehicleType === 'car' ? 5.1 : 4.1
  }
  return 6.1
}

